/**
 * Astronomical Fallback Algorithm for any year beyond 2035
 * Computes approximate full moons based on the mean synodic month cycle (29.53058885 days).
 */
function getApproximateLunarDates(year: number): LunarHolidayConfig {
  // Epoch reference: Jan 11, 2024 New Moon (Julian Day ~ 2460320.5)
  // Approximate full moon of Pisakh (May)
  const baseDateMay = new Date(Date.UTC(year, 4, 15));
  const baseDatePchum = new Date(Date.UTC(year, 8, 25));
  const baseDateWater = new Date(Date.UTC(year, 10, 10));

  const fmt = (d: Date) => d.toISOString().split('T')[0];
  const addDays = (d: Date, days: number) => {
    const res = new Date(d);
    res.setDate(res.getDate() + days);
    return res;
  };

  return {
    khmerNewYear: { from: `${year}-04-14`, to: `${year}-04-16`, days: 3 },
    visakBochea: fmt(baseDateMay),
    royalPlowing: fmt(addDays(baseDateMay, 4)),
    pchumBen: { from: fmt(baseDatePchum), to: fmt(addDays(baseDatePchum, 2)) },
    waterFestival: { from: fmt(baseDateWater), to: fmt(addDays(baseDateWater, 2)) },
  };
}

/**
 * Find the Nth weekday in a given month (e.g. 1st Monday of March)
 */
function getNthWeekdayOfMonth(year: number, month: number, weekday: number, n: number): Date {
  const d = new Date(year, month, 1);
  let count = 0;
  while (d.getMonth() === month) {
    if (d.getDay() === weekday) {
      count++;
      if (count === n) return new Date(d);
    }
    d.setDate(d.getDate() + 1);
  }
  return new Date(year, month, 1);
}

function formatDateStr(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

