/**
 * Convert numbers to Khmer numerals (e.g. 2026 -> ២០២៦)
 */
export function toKhmerNumber(num: number | string): string {
  const khmerDigits = ['០', '១', '២', '៣', '៤', '៥', '៦', '៧', '៨', '៩'];
  return String(num).replace(/[0-9]/g, (digit) => khmerDigits[parseInt(digit, 10)]);
}

/**
 * Get Buddhist Era (ពុទ្ធសករាជ) from Gregorian Year
 * Cambodia official calendar: Gregorian year + 544 (e.g. 2026 -> 2570)
 */
export function getBuddhistYear(gregorianYear: number): number {
  return gregorianYear + 544;
}

/**
 * Format academic year string in Khmer, e.g. "២០២៥ - ២០២៦"
 */
export function formatAcademicYear(startYear: number): string {
  return `${toKhmerNumber(startYear)} - ${toKhmerNumber(startYear + 1)}`;
}

