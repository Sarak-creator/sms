/**
 * Generate holidays for a range of years, e.g. 2024 through 2028
 */
export function generateCambodiaHolidaysForYearRange(startYear: number, endYear: number): HolidayData[] {
  const all: HolidayData[] = [];
  for (let y = startYear; y <= endYear; y++) {
    all.push(...generateCambodiaHolidaysForYear(y));
  }
  return all.sort((a, b) => a.dateFrom.localeCompare(b.dateFrom));
}

/**
 * Check and ensure that holidays for a target year exist in the provided holiday list.
 * Returns the merged list and count of newly added holidays.
 */
export function ensureHolidaysForYear(
  existingHolidays: HolidayData[],
  targetYear: number
): { updatedHolidays: HolidayData[]; addedCount: number } {
  const existingMap = new Map<string, HolidayData>();
  existingHolidays.forEach((h) => existingMap.set(h.id, h));

  const generated = generateCambodiaHolidaysForYear(targetYear);
  let addedCount = 0;

  generated.forEach((gen) => {
    // If exact ID exists, do not overwrite custom edits
    if (!existingMap.has(gen.id)) {
      // Also verify no duplicate date & title exists
      const hasConflict = existingHolidays.some(
        (h) => h.dateFrom === gen.dateFrom && h.titleKhmer === gen.titleKhmer
      );
      if (!hasConflict) {
        existingMap.set(gen.id, gen);
        addedCount++;
      }
    }
  });

  const updatedHolidays = Array.from(existingMap.values()).sort((a, b) =>
    a.dateFrom.localeCompare(b.dateFrom)
  );

  return { updatedHolidays, addedCount };
}

/**
 * Check and ensure holidays for both current year and next years (currentYear .. currentYear + 2).
 * Automatically invoked when loading the calendar or switching academic years.
 */
export function ensureHolidaysForCurrentAndNextYears(
  existingHolidays: HolidayData[]
): { updatedHolidays: HolidayData[]; addedCount: number } {
  const currentYear = new Date().getFullYear();
  let currentList = [...existingHolidays];
  let totalAdded = 0;

  for (let y = currentYear - 1; y <= currentYear + 2; y++) {
    const { updatedHolidays, addedCount } = ensureHolidaysForYear(currentList, y);
    currentList = updatedHolidays;
    totalAdded += addedCount;
  }

  return { updatedHolidays: currentList, addedCount: totalAdded };
}

